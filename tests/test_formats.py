import json
import warnings

import numpy as np
import pytest

import lutlab
from lutlab import LUT, formats, testing
from lutlab.formats import cube


def test_roundtrip_json_is_lossless_and_keeps_everything(tmp_path):
    axes = [np.linspace(0, 1, s) ** 1.7 for s in (5, 6, 7)]
    lut = testing.random_lut((5, 6, 7), 3, seed=1, axes=axes).replace(
        domain=((0, 0, 0), (2, 2, 2)), name="weird", space="linear")
    p = tmp_path / "a.json"
    lut.save(p)
    back = LUT.load(p)
    assert back.allclose(lut, atol=0) and back.name == "weird" and back.space == "linear"
    assert back.domain == lut.domain
    assert all(np.allclose(a, b, atol=1e-7) for a, b in zip(back.axes, lut.axes))


def test_json_4d_and_v1_compat(tmp_path):
    lut = testing.random_lut(4, 4, seed=3)
    p = tmp_path / "x.json"
    lut.save(p)
    assert LUT.load(p).allclose(lut, atol=0)
    import base64
    v1 = {"format": "lutlab v1", "name": "old", "ndim": 3, "D": 3,
          "data": base64.b64encode(LUT.identity(3).volume.astype("<f4").tobytes()).decode()}
    (tmp_path / "old.json").write_text(json.dumps(v1))
    assert LUT.load(tmp_path / "old.json").allclose(LUT.identity(3), atol=0)
    (tmp_path / "bad.json").write_text(json.dumps({"format": "other"}))
    with pytest.raises(ValueError, match="unrecognised"):
        LUT.load(tmp_path / "bad.json")


def test_cube_roundtrip_and_axis_order(tmp_path):
    lut = testing.random_lut(9, 3, seed=2, name="grade")
    p = tmp_path / "g.cube"
    lut.save(p)
    back = LUT.load(p)
    assert np.abs(back.volume - lut.volume).max() < 1e-6 and back.name == "grade"
    # R must vary fastest: rows of the 2^3 identity
    rows = cube.dumps(LUT.identity(2)).splitlines()[4:]
    expect = ["0.000000 0.000000 0.000000", "1.000000 0.000000 0.000000",
              "0.000000 1.000000 0.000000", "1.000000 1.000000 0.000000",
              "0.000000 0.000000 1.000000"]
    assert rows[:5] == expect


def test_cube_domain_is_honoured():
    text = ("TITLE \"d\"\nLUT_3D_SIZE 2\nDOMAIN_MIN 0 0 0\nDOMAIN_MAX 2 2 2\n"
            + "\n".join(f"{r} {g} {b}" for b in (0, 1) for g in (0, 1) for r in (0, 1)))
    lut = cube.loads(text)
    assert lut.domain == ((0.0,) * 3, (2.0,) * 3)
    assert np.allclose(lut(np.array([[2, 2, 2], [0, 0, 0], [1, 1, 1]], np.float32)),
                       [[1, 1, 1], [0, 0, 0], [0.5, 0.5, 0.5]], atol=1e-6)
    assert "DOMAIN_MAX 2 2 2" in cube.dumps(lut)


def test_cube_reads_lutlab_0_1_header_and_standard_quirks():
    rows = "\n".join(f"{r} {g} {b}" for b in (0, 1) for g in (0, 1) for r in (0, 1))
    old = f"Title: old one\nDomainMin: 0 0 0\nDomainMax: 1 1 1\nDataSize: 2\nLUT_3D:\n{rows}\n"
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        lut = cube.loads(old)
    assert lut.name == "old one" and lut.allclose(LUT.identity(2))
    foundry = f'TITLE "Generated by Foundry::LUT"\n# c\nLUT_3D_SIZE 2\n{rows}\n'
    assert cube.loads(foundry).name == "Generated by Foundry::LUT"
    with pytest.warns(UserWarning, match="FANCY"):
        cube.loads(f"FANCY 1\nLUT_3D_SIZE 2\n{rows}")


def test_cube_rejects_what_it_cannot_represent():
    with pytest.raises(ValueError, match="1D"):
        cube.loads("LUT_1D_SIZE 4\n0 0 0\n")
    with pytest.raises(ValueError, match="not a 3D"):
        cube.loads("LUT_3D_SIZE 2\n0 0 0\n1 1 1\n")
    with pytest.raises(ValueError, match="3D"):
        cube.dumps(testing.random_lut(4, 4))
    with pytest.raises(ValueError, match="equal axis sizes"):
        cube.dumps(LUT(np.zeros((3, 4, 5, 3))))
    rect = testing.random_lut(5, 3, axes=[np.linspace(0, 1, 5) ** 2] * 3)
    with pytest.raises(ValueError, match="uniform"):
        cube.dumps(rect)


def test_npy_and_dispatch(tmp_path):
    lut = testing.random_lut(5, 3, seed=1)
    lut.save(tmp_path / "a.npy")
    assert LUT.load(tmp_path / "a.npy").allclose(lut, atol=0)
    with pytest.raises(ValueError, match="custom domain"):
        lut.replace(domain=(0, 2)).save(tmp_path / "b.npy")
    with pytest.raises(ValueError, match="unknown LUT format"):
        LUT.load(tmp_path / "a.xyz")
    lut.save(tmp_path / "noext", format="json")
    assert LUT.load(tmp_path / "noext", format="json").allclose(lut, atol=0)
    assert formats.formats() == [".cube", ".json", ".npy", ".png"]


def test_hald_roundtrip_by_bit_depth(tmp_path):
    pytest.importorskip("cv2")
    for bd, top in ((8, 255.0), (16, 65535.0)):
        lut = testing.random_lut(17, 3, seed=7, name="hald").to_bit_depth(bd)
        p = tmp_path / f"h_{bd}.hald.png"
        lut.save(p)
        back = LUT.load(p)
        assert back.sizes == (17, 17, 17)
        assert back.bit_depth == bd
        assert np.abs(back.volume - lut.volume).max() <= 1.0 / top + 1e-5


def test_convert_cli(tmp_path):
    from lutlab.__main__ import main
    testing.random_lut(5, 3, seed=1).save(tmp_path / "a.cube")
    assert main(["convert", str(tmp_path / "a.cube"), str(tmp_path / "a.json")]) == 0
    assert LUT.load(tmp_path / "a.json").shape == (5, 5, 5, 3)
    assert main(["convert"]) == 2
